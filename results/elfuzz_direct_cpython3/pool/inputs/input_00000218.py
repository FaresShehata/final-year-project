class SortedList(Generic[T]):
    """Keeps elements sorted using bisect."""
    def __init__(self, iterable=None):
        """
        >>> sl = SortedList(iterable=[7])
        >>> len(sl)
        1
        >>> sl.sort_key
        -7
        >>> sl.sort(reverse=True)
        >>> sl.append(4)
        >>> len(sl)
        2
        >>> sl.pop(0)
        4
        """
        super().__setattr__("_container", [])
        if iterable is not None: self.extend(iterable)

    def __repr__(self):
        contents = ", ".join(map(repr, self))
        return "{}({})".format(type(self).__name__, contents)

    def __str__(self):
        items = ', '.join(str(item) for item in self)
        return '[' + items + ']'

    def __len__(self): return len(self._container)
    def __iter__(self): return iter(self._container)
    def __contains__(self, item): return item in self._container
    def __getitem__(self, idx): return self._container[idx]
    def __setitem__(self, idx, value): self._container[idx] = value
    def __delitem__(self, idx): del self._container[idx]
    def clear(self): del self._container[:]

    def extend(self, iterable):
        self._container.extend(iterable)
        bisect.insort_right(self._container, iterable[-1])

    def insert(self, index, value):
        bisect.insort_right(self._container, value, index=index)

    def append(self, value):
        bisect.insort_right(self._container, value)

    def pop(self, index=-1):
        popped = self[index]
        del self._container[index]
        return popped

    def remove(self, value):
        index = self.index(value)
        del self[index]


