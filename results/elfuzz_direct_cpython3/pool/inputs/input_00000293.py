# ─── GENERATORS ───────────────────────────────────────────────────────────────


@contextlib.contextmanager
def mock(name: str, kwargs: dict[str, Any]):
    """Context manager that mocks an attribute.

    Args:
        name: Attribute to be mocked.
        kwargs: Arguments for the `setattr` call.

    Example:

        >>> with mock('foo', {'bar': 'baz'}):
        ...     foo.bar
        'baz'
    """
    mangled = f'_{type(mock).__module__}{type(mock).__name__}_{name}'
    original = getattr(type(mock), mangled, None)
    try:
        setattr(type(mock), mangled, types.SimpleNamespace(**kwargs))
        yield
    finally:
        if original is None:
            delattr(type(mock), mangled)
        else:
            setattr(type(mock), mangled, original)


