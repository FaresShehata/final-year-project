def dump_as_pickle(obj: Any) -> bytes:
    """Dump an object as a pickle using the built-in pickle module."""
    with io.BytesIO() as buf:
        pickle.dump(obj, buf)
        return buf.getvalue()


def load_from_pickle(data: bytes) -> Any:
    """Load an object from pickled data using the modern pickle module."""
    with io.BytesIO(data) as buf:
        return pickle.load(buf)


