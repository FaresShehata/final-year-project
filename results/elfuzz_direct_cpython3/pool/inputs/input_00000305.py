# ── Generic container ─────────────────────────────────────────────────────────

class SortedList(Generic[T]):
    """Keeps elements sorted using bisect."""

    def __init__(self) -> None:
        self._data: list[T] = []

    def add(self, item: T) -> None:
        bisect.insort(self._data, item)  # type: ignore[arg-type]

    def discard(self, item: T) -> None:
        idx = bisect.bisect_left(self._data, item)  # type: ignore[arg-type]
        if idx < len(self._data) and self._data[idx] == item:
            self._data.pop(idx)

    def __iter__(self) -> Iterator[T]:
        return iter(self._data)

    def __len__(self) -> int:
        return len(self._data)

    def __repr__(self) -> str:
        return f"SortedList({self._data!r})"


# ── Async machinery ───────────────────────────────────────────────────────────

async def task_sleep(seconds: int = 1) -> None:
    await asyncio.sleep(seconds)


def task_timer(fn: Callable[..., Awaitable]) -> Callable[..., Awaitable]:                  # noqa: E731
    """Decorator that wraps `fn` so it can be cancelled by task_cancel(), e.g.

       >>> timer_task = task_timer(slow_computation())
       >>> task_cancel(timer_task)

    """

    async def wrapper(*args, **kwargs) -> Any:
        fut = asyncio.ensure_future(fn(*args, **kwargs))
        try:
            return await fut
        finally:
            await task_cancel(fut)

    return wrapper


@task_timer
async def slow_computation() -> int:
    await task_sleep(2)
    return 42


