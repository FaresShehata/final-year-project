# ── Types, signatures, metadata ──────────────────────────────────────────────

def sigs(cls):
    return set(itertools.chain.from_iterable(getattr(cls, k).__annotations__.values()
                                             for k in dir(cls)))


def annotated(sig):
    cls = sig["return"]
    return {
        "name": cls.__qualname__,
        "doc": cls.__doc__,
        "params": {
            name: param.annotation
            for name, param in inspect.signature(cls).parameters.items()
            if hasattr(param.annotation, '__module__')
        },
        "returns": {
            name: param.annotation
            for name, param in inspect.signature(cls).parameters.items()
            if param.kind == inspect.Parameter.VAR_KEYWORD
        }
    }


def annotate(cls):
    def decorator(func):
        func.__signature__ = sigs(cls)
        func.__annotated__ = annotated(cls)
        return func
    return decorator


