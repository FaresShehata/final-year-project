@dataclasses.dataclass(order=True, frozen=False, slots=True)
class Point:
    x: float
    y: float

    def distance(self, other: Point) -> float:
        return ((self.x - other.x) ** 2 + (self.y - other.y) ** 2) ** 0.5


@dataclasses.dataclass
class Task:
    id: int
    name: str
    priority: Priority = Priority.NORMAL
    status: Status = dataclasses.field(default=Status.PENDING)
    tags: list[str] = dataclasses.field(default_factory=list)
    metadata: dict = dataclasses.field(default_factory=dict)
    _history: list[Status] = dataclasses.field(default_factory=list, repr=False)

    # comparison key ignores status
    sort_key: int = dataclasses.field(init=False, repr=False)

    def __post_init__(self) -> None:
        object.__setattr__(self, "sort_key", -int(self.priority))

    def transition(self, new_status: Status) -> None:
        self._history.append(self.status)
        self.status = new_status

    def to_dict(self) -> dict:
        return {
            "id":         self.id,
            "name":       self.name,
            "priority":   self.priority.value,
            "status":     self.status.value,
            "tags":       self.tags,
            "metadata":   self.metadata,
            "_history":   self._history,
            "sort_key":   self.sort_key,
        }

    @classmethod
    def from_dict(cls, data: dict) -> Task:
        return cls(**data)


def print_task(task: Task) -> None:
    print(json.dumps(task.to_dict(), indent="  "), flush=True)


async def execute_tasks(tasks: list[Task]) -> None:
    for task in tasks:
        print(f"[{task.id}] {task.name}")
        await asyncio.sleep(random.uniform(0.3, 4))
        if task.name == "critical":
            raise RuntimeError(f"{task.id}: critical failure")
        task.transition(Status.SUCCESS)
        print_task(task)


async def main() -> None:
    # The `run` method of asyncio Tasks runs the Task's coroutine until completion.
    # In this case, we can use nested calls to `run` to run multiple tasks concurrently.

    tasks = [Task(i) for i in range(6)]
    for task in tasks:
        task.tags.extend(["tag-1"] * random.randint(1, 3))
        task.metadata["key"] = f"value-{random.randint(1, 9)}"
    tasks = sorted([t for t in tasks if len(t.tags) > 1], reverse=True)

    for task in tasks:
        print_task(task)
        task.transition(Status.RUNNING)

    await asyncio.gather(
        *[execute_tasks([tasks[i]]) for i in range(len(tasks))],
        *[execute_tasks([tasks[random.randrange(len(tasks))]]) for _ in range(8)],
    )

    for task in tasks:
        print_task(task)


loop = asyncio.get_event_loop()
try:
    loop.run_until_complete(main())
finally:
    loop.close()


