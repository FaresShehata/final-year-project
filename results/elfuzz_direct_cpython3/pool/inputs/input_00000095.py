def round_half_even(n: float) -> int:
    r"""Round half-way values to the nearest even number."""
    d = n % 1
    if d < 0.5:
        return int(n)
    if d >= 0.5 or d == 0.5 and n % 2 == 0:
        return int(copysign(round(abs(n)), n))
    return int(copysign(-round(abs(n)), n))

