def validate(obj: V, schema: dict[str, Any]) -> bool:
    if obj is None:
        return False
    elif "type" not in schema:
        raise ValueError(f"No type specified for {obj}")
    elif schema["type"] == "list":
        if "items" not in schema or "minItems" not in schema or "maxItems" not in schema:
            raise ValueError(f"Missing required fields for {obj} schema")
        items_schema: dict[str, Any] = schema["items"]
        return all(validate(item, items_schema) for item in obj)
    else:
        raise NotImplementedError()


def convert(obj: V, schema: dict[str, Any], *, context: dict = {}) -> T:
    if obj is None:
        raise TypeError(f"{context=} expects a {schema['type']}, got {obj!r}")

    elif "type" not in schema:
        raise ValueError(f"No type specified for {obj}")

    elif schema["type"] == "list":
        if "items" not in schema or "minItems" not in schema or "maxItems" not in schema:
            raise ValueError(f"Missing required fields for {obj} schema")

        items_schema: dict[str, Any] = schema["items"]
        try:
            iterable = iter(obj)
            return [convert(next(iterable), items_schema, context=f"{context}[{_}]") for _ in range(len(obj))]
        except StopIteration:
            raise ValueError(f"Expected at least {schema['minItems']} {schema['type']} values, but only found {len(obj)}")

    else:
        raise NotImplementedError()


