# ── Dataclasses ───────────────────────────────────────────────────────────────

@dataclasses.dataclass(order=True, frozen=False, slots=True)
class Point:
    x: float
    y: float

    def distance(self, other: Point) -> float:
        return ((self.x - other.x) ** 2 + (self.y - other.y) ** 2) ** 0.5


@dataclasses.dataclass
class Task:
    id: int
    name: str
    priority: Priority = Priority.NORMAL
    status: Status = dataclasses.field(default=Status.PENDING)
    tags: list[str] = dataclasses.field(default_factory=list)
    metadata: dict = dataclasses.field(default_factory=dict)
    _history: list[Status] = dataclasses.field(default_factory=list, repr=False)

    # comparison key ignores status
    sort_key: int = dataclasses.field(init=False, repr=False)

    def __post_init__(self) -> None:
        object.__setattr__(self, "sort_key", -int(self.priority))

    def transition(self, new_status: Status) -> None:
        self._history.append(self.status)
        self.status = new_status

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "name": self.name,
            "priority": self.priority.name,
            "status": self.status.value,
            "tags": self.tags,
        }

    @classmethod
    def from_dict(cls, data: dict) -> "Task":
        task_data = data.copy()

        del task_data["id"]
        del task_data["priority"]

        tags = task_data.pop("tags")
        task_data.pop("status")
        return cls(**task_data)


@dataclasses.dataclass
class Result:
    task_id: int
    success: bool
    message: str = ""

    def to_dict(self) -> dict:
        return {"task_id": self.task_id, "success": self.success, "message": self.message}

    @classmethod
    def from_dict(cls, data: dict) -> "Result":
        return cls(
            task_id=data["task_id"],
            success=bool(data["success"]),
            message=data.get("message"),
        )


# ── Unpacking ─────────────────────────────────────────────────────────────────

def unpack(a: tuple[int, ...], b: tuple[float, ...]):
    a_integers, b_floats = a, b
    c, d, e = a_integers, b_floats[1:]
    f, g = a_integers[-1:], b_floats[:2]
    h = b_floats[3:]

    print(f"{a} => {a_integers}")
    print(f"{b} => {b_floats}")

    print(f"c={c}, d={d}, e={e}")
    print(f"f={f}, g={g}")
    print(f"h={h}")


C = TypeVar("C")


def unpacker(x: tuple[C, ...]) -> C:
    return x[0]


def unpackers(x: tuple[C, ...]) -> Iterator[C]:
    yield from x


