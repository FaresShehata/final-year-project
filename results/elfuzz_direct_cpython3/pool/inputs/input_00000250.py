# ── Multiprocess-related helpers ───────────────────────────────────────────────

def process_pool_map(map_fn: Callable[P, T]) -> list[T]:
    """Run map on a pool of workers, using worker processes by default."""
    with Pool(processes=multiprocessing.cpu_count()) as pool:
        res = pool.map(map_fn, range(multiprocessing.cpu_count()))
    return res


def process_pool_imap(*args, **kwargs) -> Iterator[Any]:      # type: ignore[misc]
    """
    Run imap on a pool of workers.

    Returns an iterator which will yield results until the original iterable is exhausted.
    """
    with Pool(processes=multiprocessing.cpu_count(), maxtasksperchild=10) as pool:
        res = pool.imap_unordered(*args, **kwargs)
    return iter(res)


# ── Context manager helpers ────────────────────────────────────────────────────

@contextlib.contextmanager
def suppress(*exceptions, **kwds) -> Iterator[None]:
    try:
        yield
    except exceptions as e:
        pass


@contextlib.contextmanager
def redirect_stdout(new_target: TextIO) -> Iterator[None]:
    old_target = sys.stdout
    try:
        sys.stdout = new_target
        yield
    finally:
        sys.stdout = old_target


# ── Numbers-related helpers ────────────────────────────────────────────────────

def digits_of(value: numbers.Number) -> list[int]:
    """Convert integer `value` to a list of its digits, in order from least to most significant."""
    result: list[int] = []
    while value > 0:
        result.append(int(value % 10))
        value //= 10
    return result[::-1]


