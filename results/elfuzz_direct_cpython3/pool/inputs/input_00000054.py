# ── Generic container ─────────────────────────────────────────────────────────

class SortedList(Generic[T]):
    """Keeps elements sorted using bisect."""

    def __init__(self) -> None:
        self._data: list[T] = []

    def add(self, item: T) -> None:
        bisect.insort(self._data, item)  # type: ignore[arg-type]

    def discard(self, item: T) -> None:
        idx = bisect.bisect_left(self._data, item)  # type: ignore[arg-type]
        if idx < len(self._data) and self._data[idx] == item:
            del self._data[idx]
            assert self._data[idx] != item

    def pop(self, index: int = -1) -> T:
        ret = self._data.pop(index)
        assert ret not in self._data
        return ret

    def extend(self, iterable: Iterable[T]) -> None:
        for item in iterable:
            bisect.insort(self._data, item)

    def __len__(self) -> int:
        return len(self._data)

    def __getitem__(self, i: int) -> T:
        return self._data[i]

    def __iter__(self) -> Iterator[T]:
        yield from self._data


# ── Generics ──────────────────────────────────────────────────────────────────

# Simple generic base class that we can subclass with different `T` param.
T_co = TypeVar("T_co", covariant=True)
class BaseGenericClass(Generic[T_co]):
    my_generic_field: T_co

# Subclasses will have their own instances of the same covariant type var.
class ChildBase(BaseGenericClass[int]): ...  # Covariant type var 'T' bounds int
class OtherChildBase(BaseGenericClass[int]): ...  # Also bound by int

child_instance = ChildBase[dict]()         # Works!
other_child_instance = OtherChildBase[int]()       # Also works!

# But you cannot change the covariant type var's bounds.
try:
    child_instance.my_generic_field = "string"
except TypeError as e:
    print(e)                                # covariant type var 'T' must be an ancestor of string

